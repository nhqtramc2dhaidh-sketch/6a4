// Helper to generate cute avatar SVG data URI so all students look bright, distinct & guaranteed to load
export const getStudentSvgAvatar = (seed: string, gender: 'male' | 'female', index: number): string => {
  const bgColors = ['%23E0F2FE', '%23FEF3C7', '%23D1FAE5', '%23FCE7F3', '%23EDE9FE', '%23CFFAFE'];
  const bg = bgColors[index % bgColors.length];
  const hairColor = '%231E293B';
  const skin = '%23FED7AA';
  const shirtColor = gender === 'female' ? '%23F472B6' : '%2338BDF8';
  const initials = seed.split(' ').map((n) => n[0]).slice(-2).join('');

  return `data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">
    <rect width="100" height="100" rx="50" fill="${bg}"/>
    <circle cx="50" cy="46" r="23" fill="${skin}"/>
    ${
      gender === 'female'
        ? `<path d="M26,45 C24,28 35,20 50,20 C65,20 76,28 74,45 C73,42 66,28 50,28 C34,28 27,42 26,45 Z" fill="${hairColor}"/>
           <path d="M25,44 C22,58 24,68 30,70 C31,64 30,55 31,48 Z" fill="${hairColor}"/>
           <path d="M75,44 C78,58 76,68 70,70 C69,64 70,55 69,48 Z" fill="${hairColor}"/>`
        : `<path d="M28,40 C28,24 38,18 50,18 C62,18 72,24 72,40 C70,30 63,24 50,24 C37,24 30,30 28,40 Z" fill="${hairColor}"/>`
    }
    <circle cx="43" cy="45" r="2.5" fill="%230F172A"/>
    <circle cx="57" cy="45" r="2.5" fill="%230F172A"/>
    <path d="M46,53 Q50,57 54,53" stroke="%23EA580C" stroke-width="2" stroke-linecap="round" fill="none"/>
    <path d="M24,96 C26,76 38,72 50,72 C62,72 74,76 76,96 Z" fill="${shirtColor}"/>
    <polygon points="50,72 45,82 50,85 55,82" fill="%23FFFFFF"/>
    <text x="50" y="94" font-size="8" font-family="sans-serif" font-weight="bold" fill="%23FFFFFF" text-anchor="middle">${initials}</text>
  </svg>`;
};

